const assert = require('node:assert/strict');
const load = require('./lib/load-ts.cjs');
const { customSortingLimit, validateCustomSource, reviewCustomSorting } = load('src/services/custom-sorting-test.ts');
const { buildHybridPlan, completeHybridPlan } = load('src/services/hybrid-classifier.ts');
assert.throws(() => validateCustomSource());
assert.throws(() => validateCustomSource(' \n '));
assert.throws(() => validateCustomSource('x'.repeat(customSortingLimit + 1)));
assert.equal(validateCustomSource('x'.repeat(customSortingLimit)).length, customSortingLimit);
const source = '  I miss my sister.\nMy job affects my rent. I keep waking up during the night.  ';
assert.equal(validateCustomSource(source), source, 'Never rewrite the input source');
const plan = buildHybridPlan(source);
const responses = plan.requests.map((request) => JSON.stringify(Object.fromEntries(request.units.map((unit) => [unit.id, 0]))));
const merged = completeHybridPlan(plan, responses);
const localIds = plan.local.map((item) => item.id);
const review = reviewCustomSorting(source, merged, localIds);
assert.equal(review.status, 'review');
assert.deepEqual(review.items.map((item) => item.text), ['I miss my sister.', 'My job affects my rent.', 'I keep waking up during the night.']);
assert.deepEqual(review.items.map((item) => item.method), ['local', 'model', 'local']);
assert.equal(review.localCount, 2);
assert.equal(review.modelCount, 1);
assert.equal(review.items[1].category, 'Other', 'Do not overwrite a model decision');
assert.equal(review.items[1].needsReview, true);
assert.equal('topicMatches' in review, false, 'Custom input has no invented accuracy score');
assert.equal(reviewCustomSorting(source, '{}', localIds).status, 'invalid');
assert.equal(reviewCustomSorting(source, '{"1":1,"2":0,"3":12,"3":12}', localIds).status, 'invalid');
assert.equal(reviewCustomSorting(source, '{"1":999,"2":0,"3":12}', localIds).status, 'invalid');
assert.equal(reviewCustomSorting(source, merged, [1, 1]).status, 'invalid');
assert.equal(reviewCustomSorting(source, merged, [999]).status, 'invalid');
const longer = Array.from({ length: 14 }, () => 'My job affects my rent.').join(' ');
const longPlan = buildHybridPlan(longer);
assert.ok(longPlan.requests.length > 1, 'Custom input can span multiple bounded batches');
const longResponse = completeHybridPlan(longPlan, longPlan.requests.map((request) => JSON.stringify(Object.fromEntries(request.units.map((unit) => [unit.id, 0])))));
assert.equal(reviewCustomSorting(longer, longResponse).items.length, 14, 'Read all merged IDs, not just the first batch');
assert.equal(reviewCustomSorting('I miss my sister.', '{"1":1}', [1]).modelCount, 0);
// A real tablet dump exposed missing financial evidence and compound clauses.
const dump = "I am worried about tomorrow. Sometimes, I try not to think about it but I just can't take it off. I have to pay my fees all by myself and I juggle work with school life.";
const dumpPlan = buildHybridPlan(dump);
assert.equal(dumpPlan.units.length, 4, 'Separate financial clause from the independent work/school clause');
assert.deepEqual(dumpPlan.local.map((item) => [item.id, item.categoryId]), [[1, 10], [3, 3]], 'Explicit worry and financial terms are local rules, not model accuracy');
assert.deepEqual(dumpPlan.requests.flatMap((request) => request.units.map((unit) => unit.id)), [2, 4]);
assert.equal(dumpPlan.units[2].text, 'I have to pay my fees all by myself');
assert.equal(dumpPlan.units[3].text, 'and I juggle work with school life.');
assert.equal(dumpPlan.units.map((unit) => unit.text).join('').replace(/\s/g, ''), dump.replace(/\s/g, ''), 'Every original word and connector is retained');
const dumpResponses = dumpPlan.requests.map((request) => JSON.stringify(Object.fromEntries(request.units.map((unit) => [unit.id, 0]))));
const dumpReview = reviewCustomSorting(dump, completeHybridPlan(dumpPlan, dumpResponses), dumpPlan.local.map((item) => item.id));
assert.equal(dumpReview.items[1].category, 'Other', 'Vague pronouns are not assigned an invented meaning');
assert.deepEqual(dumpReview.items[3].competingTopics, ['Work', 'School']);
assert.equal(dumpReview.items[3].category, 'Other', 'Do not hide a weak model response');
const explicitMixed = 'I juggle work with school life.';
const mixedReview = reviewCustomSorting(explicitMixed, '{"1":2}');
assert.equal(mixedReview.items[0].needsReview, true, 'A valid single category can still omit another topic');
assert.deepEqual(mixedReview.items[0].competingTopics, ['Work', 'School']);
for (const text of ['I pay tuition.', 'I have fees to pay.', 'My payment is late.']) assert.ok(buildHybridPlan(text).units[0].candidateIds.includes(3), 'Money must be offered beyond the screenshot wording');
for (const text of ['I owe rent but I need sleep.', 'I miss my parents and I have an exam.']) assert.equal(buildHybridPlan(text).units.length, 2);
for (const text of ['My work and school commitments clash.', 'I work in an office and I work from home.', 'She wrote "I pay rent and I study for exams."']) assert.equal(buildHybridPlan(text).units.length, 1, 'Keep shared subjects, same topics and quoted text intact');
console.log('Custom sorting checks passed: exact source, bounds, multiple batches, method provenance, invalid responses and honest review.');
