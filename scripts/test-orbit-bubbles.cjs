const assert = require('node:assert/strict');
const load = require('./lib/load-ts.cjs');
const { checkBubbles, repairBubbles, readSorterReply, sorterPrompt, sorterCategories, validateSorterEntry, sorterEntryLimit } = load('src/services/orbit-bubbles.ts');

// The prompt must match training byte for byte.
assert.equal(sorterPrompt('cant sleep'), "Sort this journal entry into category bubbles. Use only the writer's exact words. Return JSON.\n\ncant sleep");
assert.equal(sorterCategories.length, 17);
assert.equal(validateSorterEntry('  keep spacing  '), '  keep spacing  ');
assert.throws(() => validateSorterEntry('   '));
assert.throws(() => validateSorterEntry('x'.repeat(sorterEntryLimit + 1)));

// Parity with lora_fine_tuning_orbit_model/orbit_schema.py on real validation entries,
// broken the ways the model breaks them (fixture generated by the Python code).
const cases = require('./fixtures/orbit-bubbles-parity.json');
const mismatches = [];
for (const c of cases) {
  const valid = 'bubbles' in checkBubbles(c.entry, c.bubbles);
  const repaired = repairBubbles(c.entry, c.bubbles);
  if (valid !== c.valid || JSON.stringify(repaired) !== JSON.stringify(c.repaired)) mismatches.push(c);
}
if (mismatches.length) {
  const first = mismatches[0];
  console.error(`first mismatch (${first.kind}):`, first.entry, '\nexpected', JSON.stringify(first.repaired), '\ngot     ', JSON.stringify(repairBubbles(first.entry, first.bubbles)));
}
assert.equal(mismatches.length, 0, `${mismatches.length}/${cases.length} cases differ from the Python implementation`);

// Every repaired result obeys the rules.
for (const c of cases) if (c.repaired) assert.ok('bubbles' in checkBubbles(c.entry, c.repaired), c.kind);

// Reading raw replies.
const entry = 'Church tomorrow morning, need to iron my shirt.';
const good = JSON.stringify({ bubbles: [{ category: 'Faith & Spirituality', texts: ['Church tomorrow morning,'] }, { category: 'Daily Life', texts: ['need to iron my shirt.'] }] });
assert.deepEqual(readSorterReply(entry, good), { status: 'ok', bubbles: JSON.parse(good).bubbles, repaired: false, raw: good });
const dropped = JSON.stringify({ bubbles: [{ category: 'Faith & Spirituality', texts: ['Church tomorrow morning,'] }] });
const fixed = readSorterReply(entry, dropped);
assert.equal(fixed.status, 'ok');
assert.equal(fixed.repaired, true);
assert.deepEqual(fixed.bubbles, [{ category: 'Faith & Spirituality', texts: ['Church tomorrow morning, need to iron my shirt.'] }]);
assert.equal(readSorterReply(entry, '{"bubbles": [').status, 'invalid');
assert.equal(readSorterReply(entry, '{"bubbles": [{"category": "Work", "texts": ["nothing like this"]}]}').status, 'invalid');

console.log(`orbit-bubbles: ${cases.length} parity cases match Python; reply reading checks passed.`);

// Chunked sorting.
const { sorterWindows, sortInWindows, readSorterWindows } = load('src/services/orbit-bubbles.ts');
const day = 'ok so today was a lot. woke up late again. missed the bus. mum called twice.\nrent is due friday\nmy back hurts. thank god for my sister';
const windows = sorterWindows(day);
assert.deepEqual(windows, ['ok so today was a lot. woke up late again. missed the bus.', 'mum called twice.\nrent is due friday\nmy back hurts.', 'thank god for my sister']);
for (const text of windows) assert.ok(day.includes(text));
assert.deepEqual(sorterWindows('grateful for sunny days'), ['grateful for sunny days']);
assert.ok(sorterWindows('a. ' + 'b'.repeat(400) + '. c.').length >= 2, 'a long sentence starts its own window');

(async () => {
  const replies = {
    'ok so today was a lot. woke up late again. missed the bus.': { bubbles: [{ category: 'Feelings', texts: ['ok so today was a lot.'] }, { category: 'Daily Life', texts: ['woke up late again.', 'missed the bus.'] }] },
    'mum called twice.\nrent is due friday\nmy back hurts.': { bubbles: [{ category: 'Family', texts: ['mum called twice.'] }, { category: 'Money', texts: ['rent is due friday'] }] }, // drops a sentence: repaired
  };
  const calls = [];
  const raw = await sortInWindows(day, async (text, index) => { calls.push(index); return text in replies ? JSON.stringify(replies[text]) : 'not json'; });
  assert.deepEqual(calls, [0, 1, 2]);
  const merged = readSorterReply(day, raw);
  assert.equal(merged.status, 'ok');
  assert.equal(merged.repaired, false, 'merged bubbles are already valid');
  assert.deepEqual(merged.bubbles.map((b) => b.category), ['Feelings', 'Daily Life', 'Family', 'Money', 'Other']);
  assert.deepEqual(merged.bubbles.find((b) => b.category === 'Other').texts, ['thank god for my sister'], 'an unusable window keeps its words in Other');
  const details = readSorterWindows(raw);
  assert.deepEqual(details.map((w) => [w.repaired, w.failed]), [[false, false], [true, false], [false, true]]);
  assert.equal(readSorterWindows(good), null);
  console.log('orbit-bubbles: chunked sorting checks passed.');
})().catch((error) => { console.error(error); process.exitCode = 1; });
